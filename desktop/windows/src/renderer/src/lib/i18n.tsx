const MESSAGES: Record<UiLanguage, Record<TranslationKey, string>> = {
  en: ENGLISH,
  ja: JAPANESE
}

function translate(language: UiLanguage, key: TranslationKey): string {
  return MESSAGES[language][key]
}

type I18nValue = {
  language: UiLanguage
  setLanguage: (language: UiLanguage) => void
  t: (key: TranslationKey) => string
}

const FALLBACK_VALUE: I18nValue = {
  language: 'en',
  setLanguage: () => undefined,
  t: (key) => ENGLISH[key]
}

const I18nContext = createContext<I18nValue>(FALLBACK_VALUE)

export function I18nProvider({ children }: { children: React.ReactNode }): React.JSX.Element {
  const [language, setLanguageState] = useState<UiLanguage>(() => getPreferences().uiLanguage)

  useEffect(
    () => onPreferencesChange((preferences) => setLanguageState(preferences.uiLanguage)),
    []
  )

  useEffect(() => {
    document.documentElement.lang = language
  }, [language])

  const value = useMemo<I18nValue>(
    () => ({
      language,
      setLanguage: (next) => setPreferences({ uiLanguage: next }),
      t: (key) => translate(language, key)
    }),
    [language]
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

// Context hooks conventionally live beside their provider.
// eslint-disable-next-line react-refresh/only-export-components
export function useI18n(): I18nValue {
  return useContext(I18nContext)
}
